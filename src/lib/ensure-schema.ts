export async function ensureUnikSchema() {
  if (unikOk) return;
  await ensureItensSchema();
  const client = getClient();
  await client.execute(`
    CREATE TABLE IF NOT EXISTS entrega_unik (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      data TEXT,
      tipo TEXT,
      nome TEXT,
      sku TEXT,
      quantidade DOUBLE PRECISION DEFAULT 0,
      status TEXT,
      unidade TEXT,
      estoque_aplicado BOOLEAN NOT NULL DEFAULT FALSE,
      foto_url TEXT,
      custo DOUBLE PRECISION NOT NULL DEFAULT 0,
      sugestao_venda DOUBLE PRECISION NOT NULL DEFAULT 0,
      recebido_por TEXT,
      estoque_unidade TEXT
    )
  `);
  await client.execute(`
    CREATE TABLE IF NOT EXISTS unik_vinculos (
      nome_chave TEXT PRIMARY KEY,
      sku TEXT NOT NULL,
      nome_original TEXT
    )
  `);
  const cols = await colunasTabela("entrega_unik");
  if (!cols.has("estoque_aplicado")) {
    await client.execute(
      "ALTER TABLE entrega_unik ADD COLUMN estoque_aplicado BOOLEAN NOT NULL DEFAULT FALSE"
    );
  }
  if (!cols.has("foto_url")) {
    await client.execute("ALTER TABLE entrega_unik ADD COLUMN foto_url TEXT");
  }
  if (!cols.has("custo")) {
    await client.execute("ALTER TABLE entrega_unik ADD COLUMN custo DOUBLE PRECISION NOT NULL DEFAULT 0");
  }
  if (!cols.has("sugestao_venda")) {
    await client.execute(
      "ALTER TABLE entrega_unik ADD COLUMN sugestao_venda DOUBLE PRECISION NOT NULL DEFAULT 0"
    );
  }
  if (!cols.has("recebido_por")) {
    await client.execute("ALTER TABLE entrega_unik ADD COLUMN recebido_por TEXT");
  }
  if (!cols.has("estoque_unidade")) {
    await client.execute("ALTER TABLE entrega_unik ADD COLUMN estoque_unidade TEXT");
  }
  await client.execute(`
    CREATE TABLE IF NOT EXISTS unik_loja_status (
      sku TEXT NOT NULL,
      unidade TEXT NOT NULL,
      enviado BOOLEAN NOT NULL DEFAULT FALSE,
      lancado BOOLEAN NOT NULL DEFAULT FALSE,
      PRIMARY KEY (sku, unidade)
    )
  `);
  await client.execute("CREATE INDEX IF NOT EXISTS idx_entrega_unik_data ON entrega_unik(data)");
  await client.execute("CREATE INDEX IF NOT EXISTS idx_entrega_unik_sku ON entrega_unik(sku)");
  unikOk = true;
}
